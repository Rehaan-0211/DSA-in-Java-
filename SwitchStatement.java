public class SwitchStatement {
    public static void main(String[] args) {
        int number = 4;
        switch (number) {
            case 1:
                System.out.println("Red headed Baddie");
                break;
            case 3:
                System.out.println("Goth mommy");
                break;
            case 2:
                System.out.println(
                        "Someone who genuinely loves and would do anything but never leave me and would love all parts of me without judging and would happily live with me forever and stay by my side and...damnnn");
                break;
            default:
                System.out.println("Wake up");
        }
    }
}
